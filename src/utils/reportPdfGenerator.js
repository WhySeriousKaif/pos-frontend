import jsPDF from 'jspdf'

/**
 * Format currency in Indian Rupees (INR)
 * Uses standard ASCII 'INR' to guarantee 100% clean rendering in jsPDF without character code distortion.
 */
const formatCurrency = (amount) => {
  return `INR ${(amount || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
}

/**
 * Helper to add header banner to PDF report
 */
const renderReportHeader = (doc, title, subtitle) => {
  const pageWidth = doc.internal.pageSize.getWidth()
  
  // Executive Blue Banner Header (#2563EB)
  doc.setFillColor(37, 99, 235)
  doc.rect(0, 0, pageWidth, 32, 'F')

  doc.setFontSize(16)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(255, 255, 255)
  doc.text(title.toUpperCase(), 15, 18)

  doc.setFontSize(8.5)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(224, 242, 254)
  doc.text(subtitle, 15, 26)

  doc.setFontSize(8)
  doc.text(`Generated: ${new Date().toLocaleString('en-IN')}`, pageWidth - 15, 18, { align: 'right' })
  doc.text('Bilix POS System • Confidential Report', pageWidth - 15, 26, { align: 'right' })
}

/**
 * Render table headers and rows dynamically with proportioned column widths
 */
const renderTable = (doc, startY, columns, rows) => {
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const margin = 15
  let yPos = startY

  const tableWidth = pageWidth - 2 * margin

  // Calculate Column Widths
  const totalWeight = columns.reduce((sum, col) => sum + (col.width || 10), 0)
  const colWidths = columns.map(col => ((col.width || 10) / totalWeight) * tableWidth)
  const colXs = []
  let currentX = margin
  colWidths.forEach(w => {
    colXs.push(currentX)
    currentX += w
  })

  // Header Row
  doc.setFillColor(37, 99, 235)
  doc.rect(margin, yPos, tableWidth, 9, 'F')

  doc.setFontSize(9)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(255, 255, 255)

  columns.forEach((col, idx) => {
    const x = col.align === 'right' ? colXs[idx] + colWidths[idx] - 3 : colXs[idx] + 3
    doc.text(col.header, x, yPos + 6, { align: col.align || 'left' })
  })

  yPos += 12

  // Table Body Rows
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(30, 41, 59)

  if (rows.length === 0) {
    doc.setFontSize(9)
    doc.text('No record data available for this report period.', margin + 3, yPos + 5)
    return yPos + 12
  }

  rows.forEach((row, rowIndex) => {
    // Page Break check
    if (yPos + 12 > pageHeight - 20) {
      doc.addPage()
      renderReportHeader(doc, 'EXECUTIVE REPORT', 'Page Continued')
      yPos = 40

      // Re-render Header Row on new page
      doc.setFillColor(37, 99, 235)
      doc.rect(margin, yPos, tableWidth, 9, 'F')
      doc.setFontSize(9)
      doc.setFont('helvetica', 'bold')
      doc.setTextColor(255, 255, 255)

      columns.forEach((col, idx) => {
        const x = col.align === 'right' ? colXs[idx] + colWidths[idx] - 3 : colXs[idx] + 3
        doc.text(col.header, x, yPos + 6, { align: col.align || 'left' })
      })

      yPos += 12
      doc.setFont('helvetica', 'normal')
      doc.setTextColor(30, 41, 59)
    }

    // Alternating Row Background
    if (rowIndex % 2 === 1) {
      doc.setFillColor(248, 250, 252)
      doc.rect(margin, yPos - 3, tableWidth, 10, 'F')
    }

    doc.setFontSize(8.5)
    columns.forEach((col, colIdx) => {
      let cellVal = row[col.key] !== undefined && row[col.key] !== null ? String(row[col.key]) : ''
      const cellX = col.align === 'right' ? colXs[colIdx] + colWidths[colIdx] - 3 : colXs[colIdx] + 3
      
      const maxColW = colWidths[colIdx] - 6
      if (doc.getTextWidth(cellVal) > maxColW) {
        cellVal = doc.splitTextToSize(cellVal, maxColW)[0] + '...'
      }
      doc.text(cellVal, cellX, yPos + 3, { align: col.align || 'left' })
    })

    yPos += 10
  })

  // Footer line
  doc.setDrawColor(226, 232, 240)
  doc.line(margin, pageHeight - 14, pageWidth - margin, pageHeight - 14)
  doc.setFontSize(7)
  doc.setTextColor(148, 163, 184)
  doc.text(`Generated by Bilix POS System • Confidential Operations Report`, pageWidth / 2, pageHeight - 8, { align: 'center' })

  return yPos
}

/**
 * Export Sales PDF Report
 */
export const exportSalesReportPDF = (orders) => {
  const doc = new jsPDF('landscape')
  renderReportHeader(doc, 'Branch Sales Audit Report', 'Itemized list of order transactions')

  const columns = [
    { header: 'Order ID', key: 'id', width: 15 },
    { header: 'Date & Time', key: 'date', width: 32 },
    { header: 'Customer Name', key: 'customer', width: 35 },
    { header: 'Payment Method', key: 'payment', width: 25 },
    { header: 'Status', key: 'status', width: 20 },
    { header: 'Amount', key: 'amount', align: 'right', width: 30 },
  ]

  const rows = orders.map(order => ({
    id: `#${order.id}`,
    date: order.createdAt ? new Date(order.createdAt).toLocaleString('en-IN') : 'N/A',
    customer: typeof order.customer === 'string' ? order.customer : (order.customer?.name || order.customer?.fullName || 'Walk-in Customer'),
    payment: order.paymentType || 'CASH',
    status: order.status || 'COMPLETED',
    amount: formatCurrency(order.totalAmount),
  }))

  renderTable(doc, 40, columns, rows)
  doc.save(`sales_report_${new Date().toISOString().split('T')[0]}.pdf`)
}

