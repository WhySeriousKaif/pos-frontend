/**
 * Export Complete Multi-Page Shift Summary PDF Report
 */
export const exportShiftSummaryReportPDF = (shiftData) => {
  const doc = new jsPDF()
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const margin = 15
  let yPos = margin

  const cashierName = shiftData?.cashier?.fullName || shiftData?.cashier?.email || 'Cashier'
  const startTime = shiftData?.shiftStart ? new Date(shiftData.shiftStart).toLocaleString('en-IN') : 'N/A'
  const endTime = shiftData?.shiftEnd ? new Date(shiftData.shiftEnd).toLocaleString('en-IN') : 'Shift Active'

  // Header Banner
  renderReportHeader(doc, 'Cashier Shift Summary Report', `Cashier: ${cashierName} • Started: ${startTime}`)

  yPos = 42

  // Shift Meta Box
  doc.setFillColor(248, 250, 252)
  doc.roundedRect(margin, yPos, pageWidth - 2 * margin, 24, 2, 2, 'F')
  doc.setDrawColor(226, 232, 240)
  doc.roundedRect(margin, yPos, pageWidth - 2 * margin, 24, 2, 2, 'S')

  doc.setFontSize(9)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 41, 59)
  doc.text('SHIFT OVERVIEW', margin + 5, yPos + 6)

  doc.setFont('helvetica', 'normal')
  doc.setTextColor(71, 85, 105)
  doc.text(`Cashier Name: ${cashierName}`, margin + 5, yPos + 13)
  doc.text(`Shift Start: ${startTime}`, margin + 5, yPos + 19)

  doc.text(`Status: ${shiftData?.shiftEnd ? 'Completed' : 'ACTIVE'}`, pageWidth / 2 + 10, yPos + 13)
  doc.text(`Shift End: ${endTime}`, pageWidth / 2 + 10, yPos + 19)

  yPos += 30

  // KPI Summary Table
  doc.setFontSize(10)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 41, 59)
  doc.text('1. FINANCIAL PERFORMANCE SUMMARY', margin, yPos)
  yPos += 5

  const kpiColumns = [
    { header: 'Metric', key: 'metric', width: 50 },
    { header: 'Orders Count', key: 'orders', width: 25 },
    { header: 'Amount', key: 'amount', align: 'right', width: 25 },
  ]

  const kpiRows = [
    { metric: 'Gross Sales Revenue', orders: shiftData?.totalOrders || 0, amount: formatCurrency(shiftData?.totalSales) },
    { metric: 'Total Refund Deductions', orders: shiftData?.refunds?.length || 0, amount: `- ${formatCurrency(shiftData?.totalRefunds)}` },
    { metric: 'Net Register Revenue', orders: shiftData?.totalOrders || 0, amount: formatCurrency(shiftData?.netSale) },
  ]

  yPos = renderTable(doc, yPos, kpiColumns, kpiRows)
  yPos += 10

  // Payment Breakdown
  doc.setFontSize(10)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 41, 59)
  doc.text('2. PAYMENT METHODS BREAKDOWN', margin, yPos)
  yPos += 5

  const payColumns = [
    { header: 'Payment Method', key: 'method', width: 40 },
    { header: 'Transaction Count', key: 'count', width: 30 },
    { header: 'Share (%)', key: 'share', width: 30 },
    { header: 'Total Collected', key: 'total', align: 'right', width: 40 },
  ]

  const paySummaries = shiftData?.paymentSummaries || []
  const payRows = paySummaries.map(p => ({
    method: p.type || 'CASH',
    count: p.transactionCount || 0,
    share: `${(p.percentage || 0).toFixed(1)}%`,
    total: formatCurrency(p.totalAmount),
  }))

  yPos = renderTable(doc, yPos, payColumns, payRows.length > 0 ? payRows : [{ method: 'Cash', count: shiftData?.totalOrders || 0, share: '100%', total: formatCurrency(shiftData?.totalSales) }])
  yPos += 10

  // Top Selling Items
  doc.setFontSize(10)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 41, 59)
  doc.text('3. TOP SELLING PRODUCTS', margin, yPos)
  yPos += 5

  const topColumns = [
    { header: 'Product Name', key: 'name', width: 60 },
    { header: 'Qty Sold', key: 'qty', width: 25 },
    { header: 'Unit Price', key: 'price', align: 'right', width: 30 },
    { header: 'Total Revenue', key: 'total', align: 'right', width: 35 },
  ]

  const topProducts = shiftData?.topSellingProducts || []
  const topRows = topProducts.map(p => ({
    name: p.name || 'Product',
    qty: p.quantity || 1,
    price: formatCurrency(p.sellingPrice),
    total: formatCurrency((p.quantity || 1) * (p.sellingPrice || 0)),
  }))

  renderTable(doc, yPos, topColumns, topRows)

  doc.save(`shift_summary_${cashierName.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`)
}

